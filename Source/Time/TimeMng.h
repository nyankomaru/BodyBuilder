#pragma once
#include <string>
#include <vector>

//------------------------------------------------------------
// ■ ミニゲーム用タイマー・パターンデータ
//------------------------------------------------------------
struct TimeData {
    float maxTime;       // パターン全体の最大時間
    float normalStart;   // ノーマル判定開始時間
    float normalEnd;     // ノーマル判定終了時間
    float goodStart;     // グッド判定開始時間
    float goodEnd;       // グッド判定終了時間
};

//------------------------------------------------------------
// ■ タイムマネージャクラス
//    ミニゲームのタイミング管理を行う
//------------------------------------------------------------
class TimeMng
{
public:
    //--------------------------------------------------------
    // 初期化
    // - ファイルからタイムパターンをロードする
    //--------------------------------------------------------
    void Init(const char* filename);

    //--------------------------------------------------------
    // 更新
    // - 毎フレーム呼び出し
    // - 経過時間の更新、端到達チェックなど
    //--------------------------------------------------------
    void Update(float deltaTime);

    //--------------------------------------------------------
    // リセット
    // - タイマーを0に戻す
    // - 新しいランダムパターンを選択
    //--------------------------------------------------------
    void Reset();

    //--------------------------------------------------------
    // パターン設定
    // - 指定されたインデックスのパターンを選択
    //--------------------------------------------------------
    void SetPattern(int index);

    //--------------------------------------------------------
    // 現在のパターン取得
    //--------------------------------------------------------
    const TimeData& GetCurrent() const { return mCurrent; }

    //--------------------------------------------------------
    // タイマー取得
    //--------------------------------------------------------
    float GetTimer() const { return mTimer; }

    //--------------------------------------------------------
    // 端到達判定
    // - true: カーソルが端まで到達した
    //--------------------------------------------------------
    bool IsReachedEnd() const { return mReachedEnd; }

    //--------------------------------------------------------
    // 移動方向判定
    // - true: 右方向
    // - false: 左方向
    //--------------------------------------------------------
    bool IsMovingRight() const { return mMovingRight; }

    //現在の最大タイム
    float GetMaxTime()const { return mCurrent.maxTime; }

private:
    std::vector<TimeData> mPatterns;   // 全パターンリスト
    TimeData mCurrent;                 // 現在選択されているパターン
    float mTimer = 0.f;                // 経過時間
    bool mReachedEnd = false;          // 端に到達したかどうか
    bool mMovingRight = true;          // 現在のカーソル移動方向（true=右, false=左）
};

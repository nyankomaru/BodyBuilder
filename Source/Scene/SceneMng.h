#pragma once
#include "Scene.h"

//============================================================
// ■ SceneMng
//   ゲーム内のシーン遷移を管理するクラス。
//   現在のシーンの初期化・更新・描画・終了を統括。
//============================================================
class SceneMng
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   ゲーム開始時に呼び出す。
    //   startScene で指定したシーンからスタート。
    //--------------------------------------------------------
    void Init(SceneType startScene);

    //--------------------------------------------------------
    // ■ 終了
    //   現在のシーンを終了し、リソース解放。
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出され、現在のシーンを更新。
    //   シーン切り替え処理もここで実行可能。
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出され、現在のシーンを描画。
    //--------------------------------------------------------
    void Render();

private:
    //--------------------------------------------------------
    // ■ 内部処理
    //--------------------------------------------------------

    // 新しいシーンを開始する
    void _beginScene(SceneType newScene);

    // 現在のシーンを終了する
    void _endCurrentScene();

private:
    //--------------------------------------------------------
    // ■ メンバー変数
    //--------------------------------------------------------

    SceneType mCurrentScene; // 現在のシーン
    SceneType mNextScene;    // 次に切り替えるシーン

    Scene* mpScene;          // 現在動作中のシーンクラスのポインタ
};

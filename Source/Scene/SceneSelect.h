#pragma once
#include "Scene.h"
#include <string>

//============================================================
// ■ SceneSelect
//   セレクトシーン（Select）の具体的なシーンクラス。
//   Scene を継承しており、次に進むシーンを選択する画面を担当。
//============================================================
class SceneSelect : public Scene
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   シーン開始時に呼び出される
    //   - 選択画面用のリソース読み込みや初期状態設定を行う
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 終了
    //   シーン終了時に呼び出される
    //   - 選択画面用リソースの解放や状態整理を行う
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出される
    //   - 入力操作に応じて選択肢を移動
    //   - 決定操作で mNextScene を設定
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出される
    //   - 選択画面のテキストやUI、キャラクター描画を行う
    //--------------------------------------------------------
    void Render();

private:
    int mSelectedIndex = 0;               // 現在選択中のインデックス (0 ~ kSceneCount-1)

    static const int kSceneCount = 2;     // 選択可能なシーンの数
    SceneType mSceneList[kSceneCount] = { // 選択可能なシーンリスト
        SceneType::Training,
        SceneType::Menu,
    };

    const std::string menuLabels[kSceneCount] = { // 選択肢ラベル
        "筋トレするか？",
        "ステータスを見るか？",
    };

    Texture mTexture;  // 背景や装飾用テクスチャ
    Sprite mSprite;    // 背景や装飾用スプライト
};

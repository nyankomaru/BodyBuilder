//============================================================
// ■ Scene
//   ゲーム内の各シーン（タイトル・セレクト・トレーニングなど）
//   の共通基底クラス。
//   派生クラスで Init/Term/Update/Render をオーバーライドして使用。
//============================================================
class Scene
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   シーン開始時に呼び出される。
    //   派生クラスで必要なリソースのロードや初期化を行う。
    //--------------------------------------------------------
    virtual void Init();

    //--------------------------------------------------------
    // ■ 終了
    //   シーン終了時に呼び出される。
    //   派生クラスでリソースの解放や状態の整理を行う。
    //--------------------------------------------------------
    virtual void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出される。
    //   入力処理やゲームオブジェクトの更新などを行う。
    //--------------------------------------------------------
    virtual void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出される。
    //   シーン内のゲームオブジェクトやUIの描画処理を行う。
    //--------------------------------------------------------
    virtual void Render();

    //--------------------------------------------------------
    // ■ 次のシーンを取得
    //   現在のシーンが終了して次のシーンへ遷移する際に使用。
    //--------------------------------------------------------
    SceneType GetNextScene();

protected:
    //--------------------------------------------------------
    // ■ メンバー変数
    //--------------------------------------------------------

    // 次に遷移するシーン
    // SceneMng が使用してシーン切替を管理する
    SceneType mNextScene;
};

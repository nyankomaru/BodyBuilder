#include "SceneTitle.h"
#include "Fwk/Framework.h"

//============================================================
// ■ 初期化
//   - タイトル画面の各種リソースを初期化
//   - セーブデータ読み込み、背景・プレイヤー・タイトルロゴの初期化
//============================================================
void SceneTitle::Init() {
    // セーブデータを読み込む
    GetDataMng()->Load("Assets\\Data\\SaveData.kv");

    // 次に遷移するシーンをなしに設定（初期状態）
    mNextScene = SceneType::None;

    // 背景オブジェクトを初期化
    GetBG()->Init();

    // プレイヤーオブジェクトを初期化
    GetPlayer()->Init();

    // タイトルロゴ用テクスチャの読み込み
    mTexture.Load("Images\\title.png");

    // タイトルロゴスプライトの初期化
    mSprite.Init();
    mSprite.SetTexture(mTexture);
    mSprite.SetSize(1010, 714);   // サイズ設定
    mSprite.SetPosition(0, 0);    // 画面左上に配置
    mSprite.SetVisible(true);     // 表示有効
}

//============================================================
// ■ 終了
//   - 使用したリソースを解放
//   - 背景、プレイヤー、スプライトの終了処理
//============================================================
void SceneTitle::Term() {
    // タイトルロゴ用テクスチャを解放
    mTexture.Unload();

    // スプライトの終了処理
    mSprite.Term();

    // プレイヤーを描画してリソースを解放
    GetPlayer()->Render();

    // 背景オブジェクトを終了
    GetBG()->Term();
}

//============================================================
// ■ 更新
//   - 入力チェックを行い、Zキーで次のシーンへ遷移
//   - Zキー未押下時はプレイヤーの更新のみ行う
//============================================================
void SceneTitle::Update() {
    if (Input_I->IsKeyDown('Z')) {
        // Zキー押下 → 選択画面へ遷移
        mNextScene = SceneType::Select;
    }
    else {
        // Zキー未押下 → プレイヤーの更新
        GetPlayer()->Update();
    }
}

//============================================================
// ■ 描画
//   - 背景、プレイヤー、タイトルロゴを描画
//============================================================
void SceneTitle::Render() {
    // 背景描画
    GetBG()->Render();

    // プレイヤー描画
    GetPlayer()->Render();

    // タイトルロゴ描画
    mSprite.Draw();
}

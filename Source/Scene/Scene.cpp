#include "Scene.h"
#include "Fwk/Framework.h"

//============================================================
// ■ Scene 基底クラス実装
//   各シーン（タイトル・セレクト・トレーニングなど）の共通基底
//   デフォルトでは何も処理せず、派生クラスでオーバーライドして使用
//============================================================

//------------------------------------------------------------
// ■ 初期化
//   シーン開始時に呼び出される
//   - デフォルトでは次のシーンを None に設定
//------------------------------------------------------------
void Scene::Init() {
    // 次のシーンは未設定として None に初期化
    mNextScene = SceneType::None;
}

//------------------------------------------------------------
// ■ 終了
//   シーン終了時に呼び出される
//   - デフォルトでは何も処理しない
//------------------------------------------------------------
void Scene::Term() {
    // デフォルト処理なし
}

//------------------------------------------------------------
// ■ 更新
//   毎フレーム呼び出される
//   - 入力処理やゲームオブジェクト更新は派生クラスで実装
//------------------------------------------------------------
void Scene::Update() {
    // デフォルト処理なし
}

//------------------------------------------------------------
// ■ 描画
//   毎フレーム呼び出される
//   - 派生クラスでオブジェクトやUI描画を実装
//------------------------------------------------------------
void Scene::Render() {
    // デフォルト処理なし
}

//------------------------------------------------------------
// ■ 次のシーンを取得
//   SceneMng が現在シーン終了時に遷移先を確認するために使用
//------------------------------------------------------------
SceneType Scene::GetNextScene() {
    return mNextScene;
}

#pragma once
#include "Scene.h"
#include "Enemy/Enemy.h"
#include "Fwk/Graphics.h"

//============================================================
// ■ SceneContest
//   大会シーン（Contest）の具体的なシーンクラス。
//   Scene を継承しており、タイトルやセレクトとは異なる
//   大会用の更新・描画処理を実装。
//============================================================
class SceneContest : public Scene
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   シーン開始時に呼び出される
    //   - 大会用のリソース読み込みや状態初期化を行う
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 終了
    //   シーン終了時に呼び出される
    //   - 大会用のリソース解放や状態整理を行う
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出される
    //   - 大会シーンのゲーム進行、入力処理、時間管理などを行う
    //   - mNextScene の更新もここで行う
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出される
    //   - 大会シーンの UI やキャラクターの描画を行う
    //--------------------------------------------------------
    void Render();

    // ★追加：GameClear側が取得できるように
    int GetContestScore() const { return mContest.GetScore(); }
    int GetContestRank()  const { return mContest.GetRank(); }

private:
    Player* mPlayer = nullptr;                  // プレイヤーオブジェクトへのポインタ
    std::vector<EnemyStatus> mEnemies;          // 9人の敵ステータス
    Contest mContest;                           // 大会結果管理クラス

    Texture mTexture;
    Sprite mSprite;
};

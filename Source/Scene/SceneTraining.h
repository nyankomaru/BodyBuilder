#pragma once
#include "Scene.h"
#include "MiniGame/MiniGameMng.h"
#include "Time/TimeMng.h"
#include "GameDef.h"
#include "UI/UIMng.h"
#include "GameObjectMng/GameObjectMng.h"

//============================================================
// ■ トレーニングシーンクラス
//   - Sceneクラスを継承
//   - ミニゲーム選択と実行、ステータス管理を行う
//============================================================
class SceneTraining : public Scene
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   - シーン開始時に呼び出す
    //   - 背景・UI・プレイヤー・ミニゲームマネージャの初期化
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 終了
    //   - シーン終了時に呼び出す
    //   - 各オブジェクトのリソース解放
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   - 毎フレーム呼び出される
    //   - ステップに応じて選択画面かプレイ画面を更新
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   - 毎フレーム呼び出される
    //   - ステップに応じて選択画面かプレイ画面を描画
    //--------------------------------------------------------
    void Render();

private:
    //--------------------------------------------------------
    // ■ 現在のステップ
    //   - TrainingStep::Select  → ゲーム選択画面
    //   - TrainingStep::Play    → ミニゲームプレイ中
    //--------------------------------------------------------
    TrainingStep mStep = TrainingStep::Select;

    //--------------------------------------------------------
    // ■ 各種マネージャ・オブジェクト
    //--------------------------------------------------------
    TimeMng mTimeMng;          // 時間管理
    UIMng mUIMng;              // UI管理
    BG mBG;                    // 背景
    Player mPlayer;            // プレイヤー
    MiniGameMng mMiniGameMng;  // ミニゲーム管理

    float mTimer = 0.f;        // ステップ用タイマー

    //--------------------------------------------------------
    // ■ ゲーム選択用
    //--------------------------------------------------------
    int mSelectedIndex = 0;    // 現在選択しているゲームのインデックス (0~4)

    static const int kGameCount = 5;  // 選択可能なミニゲームの数
    GameType mGameList[kGameCount] = {
        GameType::Barbell,
        GameType::Dumbbel,
        GameType::LatPulldown,
        GameType::RunningMachine,
        GameType::Squat,
    };

    // 選択画面に表示するラベル
    const std::string menuLabels[kGameCount] = {
        "バーベル",
        "ダンベル",
        "ラットプルダウン",
        "ランニングマシン",
        "スクワット"
    };

    //--------------------------------------------------------
    // ■ ステップ別更新・描画処理
    //   - Update_Select() : ゲーム選択画面の更新処理
    //   - Update_Play()   : ミニゲームプレイ中の更新処理
    //   - Render_Select() : ゲーム選択画面の描画処理
    //--------------------------------------------------------
    void Update_Select();
    void Update_Play();
    void Render_Select();
};

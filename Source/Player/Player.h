#pragma once
#include "GameData/StatusData.h"
#include "Fwk/Graphics.h"
#include "GameDef.h"

//============================================================
// ■ Player
//   プレイヤーキャラクターを管理するクラス。
//   各ミニゲームのステータスに応じた更新・描画・アニメーション処理を提供。
//============================================================
class Player
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   ゲーム開始時に呼び出す。
    //   テクスチャやスプライト、アニメーションを初期化。
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出され、現在のステータスに応じた動作を更新。
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出され、スプライトを画面に描画。
    //--------------------------------------------------------
    void Render();

    //--------------------------------------------------------
    // ■ 終了
    //   ゲーム終了時に呼び出す。
    //   リソース解放やアニメーション停止処理を行う。
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ ステータス操作
    //--------------------------------------------------------
    // 現在のステータスを設定
    void SetStatus(const Status status) { mStatus = status; }

    // StatusData ポインタをセット
    void SetStatusData(StatusData* statusData) { mStatusData = statusData; }

    // スコアに応じてステータスを上昇
    void IncreaseStatus(Score score);

    StatusData* GetStatusData() const { return mStatusData; }

private:
    //--------------------------------------------------------
    // ■ グラフィック関連
    //--------------------------------------------------------
    Texture mTexture;   // キャラクターのテクスチャ
    Sprite mSprite;     // スプライト描画用

    //--------------------------------------------------------
    // ■ プレイヤーステータス
    //--------------------------------------------------------
    Status mStatus = Status::RunningMachine; // 現在のステータス
    StatusData* mStatusData = nullptr;       // ステータス管理用データ
    int iStatus = 0;                         // ステータス上昇用カウンタ

    //--------------------------------------------------------
    // ■ アニメーション処理
    //--------------------------------------------------------
    // アニメーション初期化
    void _initAnimation();

    // ステータス別更新処理
    void _updateBarbell();        // バーベル時の更新
    void _updateDumbbel();        // ダンベル時の更新
    void _updateLatPulldown();    // ラットプルダウン時の更新
    void _updateRunningMachine(); // ランニングマシン時の更新
    void _updateSquat();          // スクワット時の更新
};

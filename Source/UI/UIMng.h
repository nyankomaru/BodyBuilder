#pragma once
#include "TapGauge.h"    // タップゲージの描画・更新クラス
#include "Score_UI.h"    // スコア表示用 UI クラス
#include "Timer.h"       // 残り時間表示用 Timer クラス
#include "Time/TimeMng.h" // タイムパターン管理クラス

//-----------------------------------------------------------------------------
// ■ UIMng クラス
//    ミニゲーム用の UI 管理クラス
//    - タップゲージ
//    - スコア表示
//    - タイマー表示
//    などを統合して管理
//-----------------------------------------------------------------------------
class UIMng
{
public:
    // 初期化処理
    void Init();

    // 終了処理（リソース解放など）
    void Term();

    //-----------------------------------------------------------------------------
    // 従来版 Update
    // TimeMng クラスを渡して UI を更新する
    // 互換性維持用
    //-----------------------------------------------------------------------------
    void Update(const TimeMng& timeMng);

    //-----------------------------------------------------------------------------
    // 新規 Update
    // 残り時間（秒）を直接渡して UI を更新する
    // MiniGame から呼び出す場合はこちらを使用
    //-----------------------------------------------------------------------------
    void UpdateRemaining(float remainingSeconds);

    // UI 描画
    void Render();

    //-----------------------------------------------------------------------------
    // ゲージ関連
    //-----------------------------------------------------------------------------
    // ゲージの向き（左右反転など）を設定
    void SetGaugeDirection(int dir);

    // ゲージ位置を初期値にリセット
    void ResetGaugePosition();

    // 外部からタイマー位置を変更したい場合に使用
    void SetTimerPosition(const Vector2f& pos) { mTime.SetPosition(pos); }

    //-----------------------------------------------------------------------------
    // パブリックメンバ
    //-----------------------------------------------------------------------------
    Score_UI    mScore;      // スコア表示用 UI クラス

private:
    //-----------------------------------------------------------------------------
    // プライベートメンバ
    //-----------------------------------------------------------------------------
    TapGauge mTapGauge;   // タップゲージ（入力に応じて変化）
    Timer    mTime;       // 残り時間表示用タイマー
};

#include "UIMng.h"

//-----------------------------------------------------------------------------
// 初期化
// 各 UI コンポーネントを初期化する
//-----------------------------------------------------------------------------
void UIMng::Init() {
    mTapGauge.Init();   // タップゲージの初期化
    mScore.Init();      // スコア表示の初期化
    mTime.Init();       // タイマー表示の初期化
}

//-----------------------------------------------------------------------------
// 終了処理
// 各 UI コンポーネントを終了させ、リソースを解放
//-----------------------------------------------------------------------------
void UIMng::Term() {
    mTapGauge.Term();   // タップゲージ終了
    mScore.Term();      // スコア UI 終了
    mTime.Term();       // タイマー終了
}

//-----------------------------------------------------------------------------
// 従来の Update（TimeMng を渡す）
// TimeMng の経過時間を利用して各 UI を更新する
//-----------------------------------------------------------------------------
void UIMng::Update(const TimeMng& timeMng) {
    // TapGauge は従来通り TimeMng を使った更新
    mTapGauge.Update(timeMng);

    // スコア表示更新
    mScore.Update();

    // タイマーは経過時間（TimeMng の現在タイマー値）を渡して更新
    mTime.UpdateRemaining(timeMng.GetTimer());
}

//-----------------------------------------------------------------------------
// 新規 Update：残り時間（秒）を直接渡す
// MiniGame から呼び出されることを想定
//-----------------------------------------------------------------------------
void UIMng::UpdateRemaining(float remainingSeconds) {
    // TapGauge の更新はここでは行わない（必要に応じてオーバーロードで対応可能）

    // スコア表示更新
    mScore.Update();

    // タイマー更新（残り時間を直接渡す）
    mTime.UpdateRemaining(remainingSeconds);
}

//-----------------------------------------------------------------------------
// 描画処理
// 各 UI コンポーネントを描画する
// 描画順序：TapGauge → Score → Timer
//-----------------------------------------------------------------------------
void UIMng::Render() {
    mTapGauge.Render(); // タップゲージ描画
    mScore.Render();    // スコア描画
    mTime.Render();     // タイマー描画
}

//-----------------------------------------------------------------------------
// ゲージ方向設定
//-----------------------------------------------------------------------------
void UIMng::SetGaugeDirection(int dir) {
    mTapGauge.SetDirection(dir); // ゲージの進行方向を設定
}

//-----------------------------------------------------------------------------
// ゲージ位置リセット
//-----------------------------------------------------------------------------
void UIMng::ResetGaugePosition() {
    mTapGauge.ResetPosition();   // ゲージを初期位置に戻す
}

#pragma once
#include "GameObjectMng/GameObjectMng.h"
#include "Time/TimeMng.h"
#include "Fwk/Framework.h"
#include "GameDef.h"
#include "UI/UIMng.h"
#include "BG/BG.h"
#include "Player/Player.h"
#include "GameData/DataMng.h"

//============================================================
// ■ MiniGame
//   ミニゲームの基底クラス。
//   各種ミニゲームで共通する初期化・更新・描画・終了処理を提供。
//   外部オブジェクトへのアクセス（TimeMng, UIMng, BG, Player, DataMng）も保持。
//============================================================
class MiniGame
{
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   ゲーム開始時に呼び出す。
    //   内部タイマーや状態をリセット。
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 終了
    //   ゲーム終了時に呼び出す。
    //   リソース解放や状態クリアを行う。
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ 更新
    //   毎フレーム呼び出され、ゲームロジックを更新。
    //   入力チェック、タイマー更新、スコア処理などを行う。
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画
    //   毎フレーム呼び出され、ゲームオブジェクトやUIを描画。
    //--------------------------------------------------------
    void Render();

    //--------------------------------------------------------
    // ■ 次に遷移するゲームを取得
    //   更新処理内で次ゲームへの切り替えが決まった場合に使用。
    //--------------------------------------------------------
    GameType GetNextGame() const { return mNextGame; }

    //--------------------------------------------------------
    // ■ 外部オブジェクトとの接続
    //   ミニゲーム内で必要な他オブジェクトへのポインタを設定。
    //--------------------------------------------------------
    void SetTimeMng(TimeMng* timeMng) { mTimeMng = timeMng; }
    void SetUIMng(UIMng* pUIMng) { mUIMng = pUIMng; }
    void SetBG(BG* pBG) {
        if (pBG == nullptr) {
            DebugLog("BGポインタがnullptrです");
        }
        mBG = pBG;
    }
    void SetPlayer(Player* pPlayer) { mPlayer = pPlayer; }
    void SetDataMng(DataMng* dataMng) { mDataMng = dataMng; } // ★追加

protected:
    //--------------------------------------------------------
    // ■ 次に開始するゲーム
    //--------------------------------------------------------
    GameType mNextGame;

    //--------------------------------------------------------
    // ■ 入力処理共通関数
    //   Zキー押下など共通の入力判定
    //--------------------------------------------------------
    virtual void HandleInput();

    //--------------------------------------------------------
    // ■ スコア関連
    //--------------------------------------------------------
    Score mLastScore = Score::None;    // 前回のスコア

    //--------------------------------------------------------
    // ■ 外部オブジェクト
    //--------------------------------------------------------
    DataMng* mDataMng = nullptr;       // データ管理オブジェクト
    TimeMng* mTimeMng = nullptr;       // 時間管理オブジェクト
    UIMng* mUIMng = nullptr;           // UI管理オブジェクト
    BG* mBG = nullptr;                 // 背景オブジェクト
    Player* mPlayer = nullptr;         // プレイヤーオブジェクト

    //--------------------------------------------------------
    // ■ タイマー関連
    //--------------------------------------------------------
    float mTimer = Time_I->GetDeltaTime();  // 経過時間
    float mLimitTime = 60.f;                // ゲーム制限時間

    //--------------------------------------------------------
    // ■ ゲーム状態フラグ
    //--------------------------------------------------------
    bool mShouldChange = false;             // 入力や時間切れでゲーム切替要求が出たか
    bool mIsScoreUIVisible = false;         // スコア表示フラグ
    float mScoreUIDisplayTimer = 0.f;      // スコア表示を何秒間止めるか
};

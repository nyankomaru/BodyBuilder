// MiniGameMng.h
#pragma once

#include <memory>
#include "MiniGame.h"
#include "GameDef.h"

//============================================================
// ■ MiniGameMng
//   ミニゲームの管理クラス。
//   現在のミニゲームの初期化・更新・描画・終了処理を行う。
//   次に開始するゲームや、外部オブジェクトとの接続も管理。
//============================================================
class MiniGameMng
{
public:
	//--------------------------------------------------------
	// ■ 初期化
	//   指定したゲームシーンのミニゲームを開始できる状態にする。
	//   GameType: 開始するミニゲームの種類
	//--------------------------------------------------------
	void Init(GameType GameScene);

	//--------------------------------------------------------
	// ■ 終了
	//   現在のミニゲームの終了処理を行い、リソースを解放する。
	//--------------------------------------------------------
	void Term();

	//--------------------------------------------------------
	// ■ 更新
	//   毎フレーム呼び出され、ミニゲームの状態を更新する。
	//   ゲーム進行や入力チェックなどを行う。
	//--------------------------------------------------------
	void Update();

	//--------------------------------------------------------
	// ■ 描画
	//   毎フレーム呼び出され、ミニゲームを画面に描画する。
	//--------------------------------------------------------
	void Render();

	//--------------------------------------------------------
	// ■ 新しいゲームを開始する
	//   次に開始するミニゲームを設定し、現在ゲームを切り替える。
	//--------------------------------------------------------
	void _beginGame(GameType newGame);

	//--------------------------------------------------------
	// ■ 現在のゲームを終了する
	//   現在プレイ中のミニゲームを終了し、後処理を行う。
	//--------------------------------------------------------
	void _endCurrentGame();

	//--------------------------------------------------------
	// ■ ゲーム終了判定
	//   現在のゲームが None（未設定）なら終了扱いとして true を返す
	//--------------------------------------------------------
	bool IsFinished() const;

	//--------------------------------------------------------
	// ■ 外部オブジェクトとの接続（セッター）
	//   ミニゲームで必要な他オブジェクトへのポインタを設定する
	//--------------------------------------------------------
	void SetTimeMng(TimeMng* timeMng) { mTimeMng = timeMng; }
	void SetUIMng(UIMng* pUIMng) { mUIMng = pUIMng; }
	void SetBG(BG* pBG) { mBG = pBG; }
	void SetPlayer(Player* pPlayer) { mPlayer = pPlayer; }
	void SetDataMng(DataMng* dataMng) { mDataMng = dataMng; }

	//--------------------------------------------------------
	// ■ BG 取得
	//   現在設定されている背景オブジェクトを取得
	//--------------------------------------------------------
	BG* GetBG() const { return mBG; }

private:
	//--------------------------------------------------------
	// ■ 現在のミニゲーム
	//--------------------------------------------------------
	GameType mCurrentGame;

	//--------------------------------------------------------
	// ■ 次に開始するゲーム
	//--------------------------------------------------------
	GameType mNextGame;

	//--------------------------------------------------------
	// ■ 外部オブジェクトへのポインタ
	//--------------------------------------------------------
	TimeMng* mTimeMng = nullptr;  // 時間管理オブジェクト
	MiniGame* mpGame = nullptr;   // 現在プレイ中のミニゲーム
	UIMng* mUIMng = nullptr;      // UI管理オブジェクト
	BG* mBG = nullptr;            // 背景オブジェクト
	Player* mPlayer = nullptr;    // プレイヤーオブジェクト
	DataMng* mDataMng = nullptr;  // データ管理オブジェクト
};

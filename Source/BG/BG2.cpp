#include "BG2.h"

///------------------------------------------------------------
/// @brief 背景2（ホワイトボード）クラス
/// 
/// BG2 クラスは、ミニゲームなどのサブ背景や
/// ホワイトボード風の演出背景を表示するためのクラスです。
/// BG とほぼ同様の構成ですが、別の画像（WhiteBoard.png）
/// を使用して、異なるシーンやレイヤーに対応できます。
///------------------------------------------------------------

void BG2::Init()
{
    //--------------------------------------------------------
    // ■ 背景画像の読み込み
    //   WhiteBoad.png（Imagesフォルダ内）をロードしてスプライトへ設定。
    //   ※ファイル名が "WhiteBoard.png" の場合は適宜修正。
    //--------------------------------------------------------
    mMiniGameTex.Load("Images\\WhiteBoad.png");

    //--------------------------------------------------------
    // ■ スプライトの初期化
    //   スプライトを初期化し、テクスチャ・サイズ・位置を設定。
    //   mWidth, mHeight, mX, mY はクラスのメンバ変数。
    //--------------------------------------------------------
    mMiniGameSprite.Init();
    mMiniGameSprite.SetTexture(mMiniGameTex);
    mMiniGameSprite.SetSize(mWidth, mHeight);
    mMiniGameSprite.SetPosition(mX, mY);

    //--------------------------------------------------------
    // ■ 表示設定
    //   可視状態に設定して描画対象にする。
    //--------------------------------------------------------
    mMiniGameSprite.SetVisible(true);
}

///------------------------------------------------------------
/// @brief 背景更新処理
/// 
/// 現在は静的背景のため特に処理なし。
/// 今後、ホワイトボードにアニメーションや
/// フェード演出を加える場合はここに実装する。
///------------------------------------------------------------
void BG2::Update()
{
    // （現在は処理なし）
}

///------------------------------------------------------------
/// @brief 背景描画処理
/// 
/// 事前に設定されたスプライトを描画。
/// 他オブジェクトより先に描画すれば背景として機能する。
///------------------------------------------------------------
void BG2::Render()
{
    mMiniGameSprite.Draw();
}

///------------------------------------------------------------
/// @brief 終了処理
/// 
/// テクスチャとスプライトのメモリを解放する。
/// シーン切り替え時などに呼び出してリソースリークを防ぐ。
///------------------------------------------------------------
void BG2::Term()
{
    mMiniGameTex.Unload();
    mMiniGameSprite.Term();
}
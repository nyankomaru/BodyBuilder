#pragma once
#include "Fwk/Graphics.h"

///----------------------------------------------
/// @class BG
/// @brief ミニゲームの背景（Background）を管理するクラス。
///
/// このクラスは、ゲーム背景画像を読み込み・描画する責任を持ちます。
/// - Init()   : 背景テクスチャやスプライトの初期化
/// - Update() : 更新処理（将来的にスクロールや演出を入れるための枠）
/// - Render() : 背景画像を描画
/// - Term()   : リソース解放処理
///
/// 背景は固定画像（BG.png）を想定していますが、
/// 必要に応じてサイズ変更やアニメーション対応も可能です。
///----------------------------------------------
class BG
{
public:
	//----------------------------------------------
	// ■ 初期化
	// 背景画像の読み込み、スプライトの生成、サイズ・位置設定などを行う。
	//----------------------------------------------
	void Init();

	//----------------------------------------------
	// ■ 更新処理
	// 毎フレーム呼ばれる更新関数。
	// 現在は静的背景のため空処理だが、将来的に
	// スクロールやフェード演出を追加する場合に使用する。
	//----------------------------------------------
	void Update();

	//----------------------------------------------
	// ■ 描画処理
	// 背景スプライトを画面に描画する。
	//----------------------------------------------
	void Render();

	//----------------------------------------------
	// ■ 終了処理
	// 使用したテクスチャやスプライトのメモリを解放する。
	//----------------------------------------------
	void Term();

private:
	//----------------------------------------------
	// ■ メンバ変数
	//----------------------------------------------

	/// 背景画像用のテクスチャ。
	/// BG.png（Imagesフォルダ）をロードして使用する。
	Texture mMiniGameTex;

	/// 背景描画用のスプライト。
	/// テクスチャ、サイズ、位置、可視状態を設定して使用。
	Sprite mMiniGameSprite;

	/// 背景の描画位置（左上座標）。
	/// 画面左上が (0,0) 基準。
	float mX = 0.f;
	float mY = 0.f;

	/// 背景スプライトの描画サイズ（ピクセル単位）。
	/// デフォルトは 1280x720（フルHD 16:9 の想定）。
	float mWidth = 1280.f;
	float mHeight = 720.f;
};
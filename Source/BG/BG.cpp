#include "BG.h"

//----------------------------------------------
// 背景クラス（BG）
//----------------------------------------------
// このクラスは、ミニゲームの背景画像を表示するための
// テクスチャおよびスプライトを管理します。
//----------------------------------------------

void BG::Init()
{
    //------------------------------------------
    // 背景画像の読み込みとスプライト初期化
    //------------------------------------------

    // 背景画像（BG.png）を読み込む
    // Imagesフォルダ内のBG.pngを参照
    mMiniGameTex.Load("Images\\BG.png");

    // スプライト初期化（内部状態リセット）
    mMiniGameSprite.Init();

    // スプライトにテクスチャを設定
    mMiniGameSprite.SetTexture(mMiniGameTex);

    // 表示サイズを設定（mWidth, mHeight はメンバ変数）
    // これによりスプライトがどの大きさで描画されるかを指定
    mMiniGameSprite.SetSize(mWidth, mHeight);

    // 表示位置を設定（mX, mY はメンバ変数）
    // 左上を基準に、画面内での描画位置を決定
    mMiniGameSprite.SetPosition(mX, mY);

    // スプライトを可視状態にする（非表示→表示）
    mMiniGameSprite.SetVisible(true);
}

void BG::Update()
{
    //------------------------------------------
    // 背景の更新処理（今回は特に処理なし）
    //------------------------------------------
    // 背景は静的な画像のため、現時点では更新不要。
    // 将来的にスクロールやアニメーションを入れる場合はここに記述。
}

void BG::Render()
{
    //------------------------------------------
    // 背景の描画処理
    //------------------------------------------
    // スプライトを画面に描画する。
    // Draw()は内部で設定済みのテクスチャ、位置、サイズなどを使用。
    mMiniGameSprite.Draw();
}

void BG::Term()
{
    //------------------------------------------
    // 背景の終了処理・メモリ解放
    //------------------------------------------

    // テクスチャをアンロード（メモリ解放）
    mMiniGameTex.Unload();

    // スプライトの終了処理（内部リソース解放）
    mMiniGameSprite.Term();
}
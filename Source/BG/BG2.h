#pragma once
#include "Fwk/Graphics.h"

///------------------------------------------------------------
/// @class BG2
/// @brief ミニゲーム用の第2背景（ホワイトボードなど）を表示するクラス。
///
/// BG2 は「BG」と同様に背景画像を描画するクラスですが、
/// 主に別レイヤー・別演出（例：ホワイトボード・UI背景など）
/// として使用することを目的としています。
///
/// ・画像の読み込み、描画、解放を担当
/// ・動的なアニメーションなどは現状なし（静的背景）
///
/// 使用例：
/// ```cpp
/// BG2 bg;
/// bg.Init();
/// bg.Render();
/// bg.Term();
/// ```
///------------------------------------------------------------
class BG2
{
public:
    //--------------------------------------------------------
    // ■ 初期化処理
    //   背景用のテクスチャを読み込み、スプライトを設定する。
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 更新処理
    //   現在は静的背景のため処理なし。
    //   今後フェードやアニメーションを追加する際に使用。
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 描画処理
    //   背景スプライトを画面に描画する。
    //--------------------------------------------------------
    void Render();

    //--------------------------------------------------------
    // ■ 終了処理
    //   テクスチャとスプライトを解放してメモリリークを防ぐ。
    //--------------------------------------------------------
    void Term();

private:
    //--------------------------------------------------------
    // ■ テクスチャ
    //   背景画像データ（例："Images\\WhiteBoard.png"）を保持。
    //--------------------------------------------------------
    Texture mMiniGameTex;

    //--------------------------------------------------------
    // ■ スプライト
    //   テクスチャを画面上に表示するためのスプライト情報。
    //--------------------------------------------------------
    Sprite mMiniGameSprite;

    //--------------------------------------------------------
    // ■ 背景の表示位置
    //   (mX, mY) はスプライトの左上座標。
    //   デフォルトでは画面左上(0,0)。
    //--------------------------------------------------------
    float mX = 0.f;
    float mY = 0.f;

    //--------------------------------------------------------
    // ■ 背景のサイズ
    //   読み込む画像をこのサイズで描画。
    //   ※デフォルト値は 1028x567（画像に合わせて調整）。
    //--------------------------------------------------------
    float mWidth = 1028.f;
    float mHeight = 567.f;
};
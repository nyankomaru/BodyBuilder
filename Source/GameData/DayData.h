#pragma once
#include "Data.h"

//============================================================
// ■ DayDataクラス
//   ゲーム内の「日数」や「1日の行動回数」を管理するデータクラス。
//   Data（基底クラス）を継承しており、セーブ／ロード対応を想定。
//============================================================
class DayData : public Data {
public:

    //--------------------------------------------------------
    // ■ 初期化
    // ゲーム開始時やロード失敗時のデフォルト状態を設定する。
    //   - 1日目からスタート
    //   - 当日の行動回数は0
    //   - 1日にできる最大行動回数は3
    //--------------------------------------------------------
    void Init() override {
        mCurrentDay = 1;
        mActionsToday = 0;
        mMaxActions = 3;
    }

    //--------------------------------------------------------
    // ■ 更新処理
    // 現状では特に更新処理は不要だが、
    // 日付経過などの自動処理を将来的に追加可能。
    //--------------------------------------------------------
    void Update() override {}

    //--------------------------------------------------------
    // ■ 次の日へ進む処理
    // 現在の日数を1日進め、当日の行動回数をリセット。
    //--------------------------------------------------------
    void NextDay() {
        mCurrentDay++;
        mActionsToday = 0;
    }

    //--------------------------------------------------------
    // ■ データ保存
    // 現状は未実装。
    // KeyValueFileを用いたセーブ対応時に記述予定。
    //--------------------------------------------------------
    void Save(class KeyValueFile& kv) override {}

    //--------------------------------------------------------
    // ■ データ読み込み
    // 現状は未実装。
    // KeyValueFileを用いたロード対応時に記述予定。
    //--------------------------------------------------------
    void Load(class KeyValueFile& kv) override {}

    //--------------------------------------------------------
    // ■ ゲッター群
    // データの取得用。外部から現在の状態を参照する。
    //--------------------------------------------------------
    int GetCurrentDay() const { return mCurrentDay; }     // 現在の日数を取得
    int GetActionsToday() const { return mActionsToday; } // 今日の行動回数を取得
    int GetMaxActions() const { return mMaxActions; }     // 1日の最大行動数を取得

    //--------------------------------------------------------
    // ■ 行動回数の増加
    // 1つの行動を行った際に呼び出す。
    // 行動制限チェックは外部で実装する想定。
    //--------------------------------------------------------
    void AddAction() { mActionsToday++; }

    //--------------------------------------------------------
    // ■ セッター群
    // 外部から日数や行動数を強制的に設定する。
    // セーブ／ロードやデバッグ用の操作に使用。
    //--------------------------------------------------------
    void SetCurrentDay(const int v) { mCurrentDay = v; }
    void SetActionsToday(const int v) { mActionsToday = v; }

private:

    //--------------------------------------------------------
    // ■ メンバー変数
    //--------------------------------------------------------
    int mCurrentDay = 1;    // 現在の日付（1日目スタート）
    int mActionsToday = 0;  // 今日の行動回数
    int mMaxActions = 3;    // 1日に可能な最大行動数
};

#pragma once
#include "Fwk/File/KeyValueFile.h"

///------------------------------------------------------------
/// @class Data
/// @brief ゲームデータ管理用の共通基底クラス。
///
/// ゲーム内で使用するあらゆるデータ（例：
/// ステータス、スコア、アイテム、設定など）を統一的に扱うための
/// インターフェースクラスです。
///
/// 各データ型はこのクラスを継承して、
/// 独自の初期化・保存・読み込み処理を実装します。
///
/// 例：
/// ```cpp
/// class PlayerData : public Data {
/// public:
///     void Init() override { /* 初期化 */ }
///     void Save(KeyValueFile& kv) override { /* 保存処理 */ }
///     void Load(KeyValueFile& kv) override { /* 読み込み処理 */ }
/// };
/// ```
///------------------------------------------------------------
class Data {
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   各データ型固有の初期化処理を実装する。
    //   例）スコアを0にする、状態を初期値に戻すなど。
    //--------------------------------------------------------
    virtual void Init() = 0;

    //--------------------------------------------------------
    // ■ 更新処理（任意）
    //   データをフレームごとに更新する場合に使用。
    //   通常は何もしないため、デフォルトで空実装。
    //--------------------------------------------------------
    virtual void Update() {}

    //--------------------------------------------------------
    // ■ 保存処理（純粋仮想）
    //   データを KeyValueFile に書き出す。
    //   継承クラスでキーと値を明示的に設定する。
    //
    //   例：
    //     kv.WriteInt("Score", mScore);
    //--------------------------------------------------------
    virtual void Save(KeyValueFile& kv) = 0;

    //--------------------------------------------------------
    // ■ 読み込み処理（純粋仮想）
    //   KeyValueFile からデータを読み込む。
    //
    //   例：
    //     mScore = kv.ReadInt("Score", 0);
    //--------------------------------------------------------
    virtual void Load(KeyValueFile& kv) = 0;

    //--------------------------------------------------------
    // ■ 仮想デストラクタ
    //   継承クラスを正しく破棄できるようにするために定義。
    //--------------------------------------------------------
    virtual ~Data();
};
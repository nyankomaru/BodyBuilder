#pragma once
#include "DayData.h"
#include "StatusData.h"
#include "Contest.h"

///------------------------------------------------------------
/// @class DataMng
/// @brief 各種ゲームデータ（DayData, StatusData, Contest など）
///        を一元管理するクラス。
///
/// このクラスは、ゲーム全体で扱うデータをまとめて保持し、
/// それらの初期化・更新・保存・読み込み処理を統括します。
///
/// セーブデータの保存やロードはこのクラスを通して行われ、
/// 個々のデータクラス（DayData, StatusData, Contest）は
/// DataMng 経由でアクセスします。
///------------------------------------------------------------
class DataMng {
public:
    //--------------------------------------------------------
    // ■ 初期化
    //   各データクラス（DayData / StatusData / Contest）を
    //   初期状態にリセットします。
    //   ゲーム起動時やリセット時に呼び出されます。
    //--------------------------------------------------------
    void Init();

    //--------------------------------------------------------
    // ■ 更新処理
    //   ゲーム進行中にフレーム単位でデータを更新する場合に使用。
    //   （例：日付の進行、スコア加算など）
    //--------------------------------------------------------
    void Update();

    //--------------------------------------------------------
    // ■ 終了処理
    //   使用しているデータを解放したり、
    //   保存前の後処理を行う場合に使用。
    //--------------------------------------------------------
    void Term();

    //--------------------------------------------------------
    // ■ データの保存
    //   現在のデータを指定されたファイルへ書き出します。
    //
    //   @param filename 保存先ファイル名
    //   例："SaveData.kv"
    //--------------------------------------------------------
    void Save(const char* filename);

    //--------------------------------------------------------
    // ■ データの読み込み
    //   指定されたファイルからゲームデータを復元します。
    //
    //   @param filename 読み込み対象ファイル名
    //--------------------------------------------------------
    void Load(const char* filename);

    //--------------------------------------------------------
    // ■ データの削除
    //   指定されたファイルを削除して、
    //   セーブデータをリセットします。
    //--------------------------------------------------------
    void Delete(const char* filename);

    //--------------------------------------------------------
    // ■ 各データへのアクセサ
    //   ゲームの他のシステム（UI、シーンなど）から
    //   個々のデータを安全に取得できるようにします。
    //--------------------------------------------------------
    DayData& GetDayData() { return mDayData; }           ///< 日付や進行に関するデータ
    StatusData& GetStatusData() { return mStatusData; }  ///< プレイヤーやキャラの状態データ
    Contest& GetContestData() { return mContestData; }   ///< コンテスト（スコア・順位など）データ

private:
    //--------------------------------------------------------
    // ■ メンバー変数群
    //   各データクラスの実体を保持
    //--------------------------------------------------------
    DayData mDayData;         ///< 日付データ
    StatusData mStatusData;   ///< ステータスデータ
    Contest mContestData;     ///< コンテストデータ
};
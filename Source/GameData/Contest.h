#pragma once
#include "Data.h"

///------------------------------------------------------------
/// @class Contest
/// @brief コンテスト（大会）の結果データを保持するクラス。
///
/// このクラスは、プレイヤーが参加する「コンテスト」や「競技」
/// の順位（Rank）やスコア（Score）を管理します。
///
/// 基底クラス Data から派生しており、
/// データの初期化・保存・読み込みのインターフェースを実装します。
///
/// 使用例：
/// ```cpp
/// Contest contest;
/// contest.Init();
/// contest.SetRank(1);
/// contest.SetScore(980);
/// int rank = contest.GetRank();  // => 1
/// ```
///------------------------------------------------------------
class Contest : public Data {
public:
    //--------------------------------------------------------
    // ■ 初期化処理
    //   ランクとスコアをリセット（0）する。
    //   Data からの仮想関数をオーバーライド。
    //--------------------------------------------------------
    void Init() override {
        mRank = 0;
        mScore = 0;
    }

    //--------------------------------------------------------
    // ■ データ保存処理
    //   KeyValueFile へ保存する際に呼ばれる。
    //   （現在は未実装。必要に応じて実装予定）
    //--------------------------------------------------------
    void Save(class KeyValueFile& kv) override {}

    //--------------------------------------------------------
    // ■ データ読み込み処理
    //   KeyValueFile からデータを復元する際に呼ばれる。
    //   （現在は未実装。必要に応じて実装予定）
    //--------------------------------------------------------
    void Load(class KeyValueFile& kv) override {}

    //--------------------------------------------------------
    // ■ Rank の取得
    //   @return 現在の順位（整数）
    //--------------------------------------------------------
    int GetRank() const { return mRank; }

    //--------------------------------------------------------
    // ■ Score の取得
    //   @return 現在のスコア（整数）
    //--------------------------------------------------------
    int GetScore() const { return mScore; }

    //--------------------------------------------------------
    // ■ Rank の設定
    //   @param v 新しい順位
    //--------------------------------------------------------
    void SetRank(int v) { mRank = v; }

    //--------------------------------------------------------
    // ■ Score の設定
    //   @param v 新しいスコア
    //--------------------------------------------------------
    void SetScore(int v) { mScore = v; }

private:
    //--------------------------------------------------------
    // ■ メンバ変数
    //--------------------------------------------------------

    int mRank = 0;   ///< コンテスト順位（1位 = 1、未参加時は0）
    int mScore = 0;  ///< コンテストスコア（数値が大きいほど高評価）
};
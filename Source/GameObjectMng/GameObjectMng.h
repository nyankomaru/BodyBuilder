#pragma once

#include "GameData/DataMng.h"
#include "Player/Player.h"
#include "UI/UIMng.h"
#include "BG/BG.h"
#include "BG/BG2.h"
#include "BG/BG3.h"
#include "Enemy/Enemy.h"

//============================================================
// ■ GameObjectMng
//   ゲーム内で使用する全オブジェクトを管理するヘッダー。
//   プレイヤー、UI、背景など、ゲーム内の主要オブジェクトを
//   初期化・更新・描画・終了処理する関数群と
//   オブジェクト取得用関数を提供。
//============================================================

//------------------------------------------------------------
// ■ ゲームオブジェクト初期化
//   各オブジェクト（Player、UI、BGなど）を初期化。
//   ゲーム開始時に一度だけ呼び出す。
//------------------------------------------------------------
void GameObjectInit();

//------------------------------------------------------------
// ■ ゲームオブジェクト更新
//   毎フレーム呼び出され、各オブジェクトの状態を更新。
//   プレイヤーの移動やUIの変化などを反映。
//------------------------------------------------------------
void GameObjectUpdate();

//------------------------------------------------------------
// ■ ゲームオブジェクト描画
//   毎フレーム呼び出され、各オブジェクトを画面に描画。
//   背景→プレイヤー→UIの順で描画する想定。
//------------------------------------------------------------
void GameObjectRender();

//------------------------------------------------------------
// ■ ゲームオブジェクト終了処理
//   メモリ解放やリソース破棄を行う。
//   ゲーム終了時またはシーン切り替え時に呼び出す。
//------------------------------------------------------------
void GameObjectTerm();

//============================================================
// ■ ゲームオブジェクト取得関数
//   各オブジェクトへのアクセス用。
//   注意：直接操作する場合は状態整合性に注意。
//============================================================

// データ管理オブジェクト取得
// return: DataMng* データ管理クラスのポインタ
DataMng* GetDataMng();

// プレイヤーオブジェクト取得
// return: Player* プレイヤークラスのポインタ
Player* GetPlayer();

// UI管理オブジェクト取得
// return: UIMng* UI管理クラスのポインタ
UIMng* GetUIMng();

// 背景オブジェクト(BG)取得
// return: BG* 背景クラスのポインタ
BG* GetBG();

// 背景オブジェクト(BG2)取得
// return: BG2* 背景クラスのポインタ
BG2* GetBG2();

// 背景オブジェクト(BG3)取得
// return: BG3* 背景クラスのポインタ
BG3* GetBG3();

Enemy* GetEnemy();
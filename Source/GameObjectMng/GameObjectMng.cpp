//============================================================
// ■ GameObjectMng 実装
//   ゲーム内で使用する全オブジェクトの実体と
//   初期化・更新・描画・解放処理を定義。
//============================================================

//============================================================
// ■ オブジェクト実体
//   静的に生成することで、外部からアクセス可能。
//============================================================
static DataMng gDataMng;  // データ管理オブジェクト（セーブ／ロード含む）
Player mPlayer;           // プレイヤーオブジェクト
UIMng mUIMng;             // UI管理オブジェクト
BG mBG;                   // 背景オブジェクト
BG2 mBG2;                 // 背景オブジェクト2
BG3 mBG3;                 // 背景オブジェクト3
Enemy mEnemy;

//------------------------------------------------------------
// ■ ゲームオブジェクト初期化
//   ゲーム開始時に呼び出し、各オブジェクトの初期化を行う。
//   現状はプレイヤーとUIのみ初期化。
//------------------------------------------------------------
void GameObjectInit()
{
    mPlayer.Init();  // プレイヤー初期化
    mUIMng.Init();   // UI初期化
    // ※ 背景や他オブジェクトは今後追加可能
}

//------------------------------------------------------------
// ■ ゲームオブジェクト更新
//   毎フレーム呼び出され、各オブジェクトの状態更新を行う。
//   現状は DataMng の更新のみ。
//------------------------------------------------------------
void GameObjectUpdate()
{
    gDataMng.Update();  // データ管理オブジェクト更新（時間経過や日数管理など）
    // ※ プレイヤーやUIの更新は将来的に追加可能
}

//------------------------------------------------------------
// ■ ゲームオブジェクト描画
//   毎フレーム呼び出され、画面に情報を描画。
//   現状はデバッグ表示として日付と体力のみ表示。
//------------------------------------------------------------
void GameObjectRender()
{
    // 現在の日付を画面左上に表示
    PrintText(("日数: " + std::to_string(gDataMng.GetDayData().GetCurrentDay())).c_str(), 20, 20);

    // プレイヤーの体力（Endurance）を表示
    PrintText(("体力: " + std::to_string(gDataMng.GetStatusData().GetEndurance())).c_str(), 20, 50);

    // ※ 背景やUI、プレイヤー本体の描画は別途追加可能
}

//------------------------------------------------------------
// ■ ゲームオブジェクト解放
//   ゲーム終了時またはシーン切替時に呼び出す。
//   各オブジェクトのリソースを解放。
//------------------------------------------------------------
void GameObjectTerm()
{
    gDataMng.Term();   // データ管理オブジェクト解放
    mPlayer.Term();    // プレイヤー解放
    mUIMng.Term();     // UI解放
    // ※ 背景は必要に応じて解放処理追加
}

//============================================================
// ■ オブジェクト取得用関数
//   外部からオブジェクトへアクセスする際に使用。
//============================================================

// DataMng の外部アクセス用
DataMng* GetDataMng() {
    return &gDataMng;
}

// Player の外部アクセス用
Player* GetPlayer() {
    return &mPlayer;
}

// UIMng の外部アクセス用
UIMng* GetUIMng() {
    return &mUIMng;
}

// BG の外部アクセス用
BG* GetBG() {
    return &mBG;
}

// BG2 の外部アクセス用
BG2* GetBG2() {
    return &mBG2;
}

// BG3 の外部アクセス用
BG3* GetBG3() {
    return &mBG3;
}

Enemy* GetEnemy() {
    return &mEnemy;
}
